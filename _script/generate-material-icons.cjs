const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'src/app/core/icons/material-icons.generated.ts');
const names = new Set();
const aliases = { edit_square: 'edit' };

function scan(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) scan(file);
    else if (file !== output && /\.(ts|html)$/.test(entry.name)) {
      for (const match of fs.readFileSync(file, 'utf8').matchAll(/mat:([a-z_0-9]+)/g)) names.add(match[1]);
    }
  }
}

scan(path.join(root, 'src'));
const icons = {};
for (const name of [...names].sort()) {
  const file = path.join(root, 'node_modules/@material-design-icons/svg/two-tone', `${aliases[name] || name}.svg`);
  if (!fs.existsSync(file)) throw new Error(`Icono Material no disponible: ${name}`);
  icons[name] = fs.readFileSync(file, 'utf8').trim();
}
fs.writeFileSync(output, '// Generated by _script/generate-material-icons.cjs.\n'
  + '// Keep referenced Material icons in the bundle to avoid separate HTTP requests.\n'
  + `export const MATERIAL_ICONS: Readonly<Record<string, string>> = ${JSON.stringify(icons, null, 2)};\n`);
console.log(`Incluidos ${names.size} iconos Material en el frontend.`);
